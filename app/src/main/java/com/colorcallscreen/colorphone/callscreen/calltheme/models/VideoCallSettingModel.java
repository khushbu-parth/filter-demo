package com.colorcallscreen.colorphone.callscreen.calltheme.models;


public class VideoCallSettingModel {
    private String aapPackage;
    private String icon;
    private String id;
    private String name;

    public String getAapPackage() {
        return this.aapPackage;
    }

    public String getIcon() {
        return this.icon;
    }

    public String getId() {
        return this.id;
    }

    public String getName() {
        return this.name;
    }

    public void setAapPackage(String str) {
        this.aapPackage = str;
    }

    public void setIcon(String str) {
        this.icon = str;
    }

    public void setId(String str) {
        this.id = str;
    }

    public void setName(String str) {
        this.name = str;
    }
}
